def _flash(image: Path, probe_sn: str, *, commander: str | None = None):
    exe = commander or shutil.which("commander")
    if exe is None:
        pytest.fail(
            "Required tool 'commander' not found on PATH. "
            "Ensure Simplicity Studio CLI tools are installed or configured."
        )
    subprocess.run([exe, "flash", str(image), "--serialno", probe_sn], check=True, text=True)


def _file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _image_metadata(image: Path, *, slcp: Path, board: str, project_name: str, probe_sn: str) -> dict:
    return {
        "project_name": project_name,
        "slcp": str(slcp),
        "board": board,
        "probe_sn": probe_sn,
        "image": str(image),
        "sha256": _file_sha256(image),
        "size": image.stat().st_size,
    }


def _project_output_dir(build_root: Path, slcp: Path, *, project_name: str) -> Path:
    candidates = [
        build_root / slcp.stem,
        build_root / project_name.removeprefix("ncp_ble_"),
        build_root / project_name,
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate
    return candidates[0]


def _find_prebuilt_image(build_root: Path, *, slcp: Path, project_name: str) -> Path:
    out_dir = _project_output_dir(build_root, slcp, project_name=project_name)
    candidates = list((out_dir / "cmake_gcc").rglob("*.s37")) + list((out_dir / "cmake_gcc").rglob("*.hex"))
    if not candidates:
        pytest.fail(
            "Missing prebuilt firmware image.\n"
            f"Expected build output under: {out_dir}\n"
            f"SLCP: {slcp}\n"
            "Run `just build` or `make build` before executing pytest."
        )
    return candidates[0]


def _provision_state_root(build_root: Path, dev_cfg: dict) -> Path:
    configured = dev_cfg.get("firmware", {}).get("provision_state_root")
    if configured:
        return Path(str(configured))
    return build_root


def _dut_state_path(state_root: Path) -> Path:
    return state_root / "dut_last_flashed.json"


def _tester_ready_path(state_root: Path) -> Path:
    return state_root / "tester_ready.json"


def _bootloader_state_path(state_root: Path, device_name: str) -> Path:
    return state_root / f"{device_name}_bootloader_flashed.json"


def _read_provision_state(path: Path) -> dict:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def _write_provision_state(path: Path, state: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")


def _same_image(current: dict, previous: dict | None) -> bool:
    if not previous:
        return False
    keys = ("project_name", "slcp", "board", "probe_sn", "sha256")
    return all(current.get(key) == previous.get(key) for key in keys)


def _bootloader_metadata(image: Path, *, board: str, probe_sn: str, expected_sha256: str = "") -> dict:
    return {
        "project_name": "bootloader-uart-bgapi",
        "slcp": "",
        "board": board,
        "probe_sn": probe_sn,
        "image": str(image),
        "sha256": expected_sha256 or _file_sha256(image),
        "size": image.stat().st_size,
    }


def _short_hash(image_meta: dict | None) -> str:
    if not image_meta:
        return "missing"
    return str(image_meta.get("sha256", "missing"))[:12]


def _log_flash_decision(label: str, required: dict, previous: dict | None, should_flash: bool) -> None:
    if should_flash:
        if previous:
            log.info(
                "%s flash required: hash changed %s -> %s image=%s",
                label,
                _short_hash(previous),
                _short_hash(required),
                required["image"],
            )
        else:
            log.info(
                "%s flash required: no previous state image=%s hash=%s",
                label,
                required["image"],
                _short_hash(required),
            )
        return

    log.info(
        "%s flash skipped: image unchanged image=%s hash=%s",
        label,
        required["image"],
        _short_hash(required),
    )


@pytest.fixture(autouse=True)
def ProvisionFirmware(request: pytest.FixtureRequest) -> None:
    if "Config" not in request.fixturenames:
        return

    cfg_path = str(_test_config_path(request).resolve())

    config = request.getfixturevalue("Config")
    fw = config.get("firmware", {})
    required = (
        "dut_slcp",
        "tester_slcp",
    )
    missing = [key for key in required if key not in fw]
    if missing:
        pytest.fail("Missing 'firmware' fields in test config: " + ", ".join(missing))

    dev_cfg = _effective_dev_config(request)
    build_root_str = fw.get("build_root") or dev_cfg.get("firmware", {}).get("build_root")
    if not build_root_str:
        pytest.fail(
            "Missing build root. Set dev_config.json firmware.build_root "
            "or provide firmware.build_root in test config."
        )
    build_root = Path(build_root_str)
    state_root = _provision_state_root(build_root, dev_cfg)
    dut_probe_sn = fw.get("dut_probe_sn") or dev_cfg.get("dut", {}).get("probe_sn")
    tester_probe_sn = fw.get("tester_probe_sn") or dev_cfg.get("tester", {}).get("probe_sn")
    if not dut_probe_sn or not tester_probe_sn:
        pytest.fail(
            "Missing probe serials. Set dev_config.json dut.probe_sn and tester.probe_sn "
            "or provide firmware.dut_probe_sn/tester_probe_sn in test config."
        )
    commander = _resolve_commander(dev_cfg)
    if commander is None:
        pytest.fail(
            "Required tool 'commander' not found on PATH. "
            "Ensure Simplicity Studio CLI tools are installed or configured."
        )

    dut_state_path = _dut_state_path(state_root)
    tester_state_path = _tester_ready_path(state_root)
    dut_bootloader_state_path = _bootloader_state_path(state_root, "dut")
    tester_bootloader_state_path = _bootloader_state_path(state_root, "tester")
    previous_dut_state = _read_provision_state(dut_state_path)
    previous_tester_state = _read_provision_state(tester_state_path)
    previous_dut_bootloader_state = _read_provision_state(dut_bootloader_state_path)
    previous_tester_bootloader_state = _read_provision_state(tester_bootloader_state_path)

    dut_slcp = Path(fw["dut_slcp"])
    tester_slcp = Path(fw["tester_slcp"])
    dut_image = _find_prebuilt_image(build_root, slcp=dut_slcp, project_name="ncp_ble_dut")
    tester_image = _find_prebuilt_image(build_root, slcp=tester_slcp, project_name="ncp_ble_tester")

    dut_required = _image_metadata(
        dut_image,
        slcp=dut_slcp,
        board=fw["board"],
        project_name="ncp_ble_dut",
        probe_sn=dut_probe_sn,
    )
    tester_required = _image_metadata(
        tester_image,
        slcp=tester_slcp,
        board=fw["board"],
        project_name="ncp_ble_tester",
        probe_sn=tester_probe_sn,
    )
    bootloader_image_value = str(fw.get("bootloader_image") or "").strip()
    bootloader_image = Path(bootloader_image_value) if bootloader_image_value else None
    bootloader_required_dut = None
    bootloader_required_tester = None
    if bootloader_image is not None:
        if not bootloader_image.exists():
            pytest.fail(f"Configured bootloader image does not exist: {bootloader_image}")
        bootloader_sha = str(fw.get("bootloader_image_sha256") or "")
        bootloader_required_dut = _bootloader_metadata(
            bootloader_image,
            board=fw["board"],
            probe_sn=dut_probe_sn,
            expected_sha256=bootloader_sha,
        )
        bootloader_required_tester = _bootloader_metadata(
            bootloader_image,
            board=fw["board"],
            probe_sn=tester_probe_sn,
            expected_sha256=bootloader_sha,
        )
    dut_matches = _same_image(dut_required, previous_dut_state.get("last_flashed"))
    tester_matches = _same_image(tester_required, previous_tester_state.get("last_flashed"))
    dut_bootloader_matches = (
        True if bootloader_required_dut is None
        else _same_image(bootloader_required_dut, previous_dut_bootloader_state.get("last_flashed"))
    )
    tester_bootloader_matches = (
        True if bootloader_required_tester is None
        else _same_image(bootloader_required_tester, previous_tester_bootloader_state.get("last_flashed"))
    )
    if bootloader_required_dut is not None and bootloader_required_tester is not None:
        _log_flash_decision(
            "DUT bootloader",
            bootloader_required_dut,
            previous_dut_bootloader_state.get("last_flashed"),
            not dut_bootloader_matches,
        )
        _log_flash_decision(
            "Tester bootloader",
            bootloader_required_tester,
            previous_tester_bootloader_state.get("last_flashed"),
            not tester_bootloader_matches,
        )
    _log_flash_decision("DUT", dut_required, previous_dut_state.get("last_flashed"), not dut_matches)
    _log_flash_decision("Tester", tester_required, previous_tester_state.get("last_flashed"), not tester_matches)

    if bootloader_required_dut is not None and not dut_bootloader_matches:
        _flash(bootloader_image, dut_probe_sn, commander=commander)
        log.info("DUT bootloader flashed successfully: %s", bootloader_image)
    if bootloader_required_tester is not None and not tester_bootloader_matches:
        _flash(bootloader_image, tester_probe_sn, commander=commander)
        log.info("Tester bootloader flashed successfully: %s", bootloader_image)
    if not dut_matches:
        _flash(dut_image, dut_probe_sn, commander=commander)
        log.info("DUT flashed successfully: %s", dut_image)
    if not tester_matches:
        _flash(tester_image, tester_probe_sn, commander=commander)
        log.info("Tester flashed successfully: %s", tester_image)
    if not dut_matches or not tester_matches or not dut_bootloader_matches or not tester_bootloader_matches:
        log.info("Waiting for flashed devices to settle before BGAPI open")
        time.sleep(2.0)

    if bootloader_required_dut is not None:
        _write_provision_state(
            dut_bootloader_state_path,
            {
                "cfg_path": cfg_path,
                "status": "reused" if dut_bootloader_matches else "flashed",
                "required": bootloader_required_dut,
                "last_flashed": bootloader_required_dut,
            },
        )
    if bootloader_required_tester is not None:
        _write_provision_state(
            tester_bootloader_state_path,
            {
                "cfg_path": cfg_path,
                "status": "reused" if tester_bootloader_matches else "flashed",
                "required": bootloader_required_tester,
                "last_flashed": bootloader_required_tester,
            },
        )
    _write_provision_state(
        dut_state_path,
        {
            "cfg_path": cfg_path,
            "status": "reused" if dut_matches else "flashed",
            "required": dut_required,
            "last_flashed": dut_required,
        },
    )
    _write_provision_state(
        tester_state_path,
        {
            "cfg_path": cfg_path,
            "status": "reused" if tester_matches else "flashed",
            "required": tester_required,
            "last_flashed": tester_required,
        },
    )
